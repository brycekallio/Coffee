// Writes compositions/captions.html from captions.json ([{ text, start, end }], seconds).
// After the real voiceover lands: `npx hyperframes transcribe assets/voiceover.wav --model small.en`,
// regroup its words into 3-5 word groups in captions.json, then run `node tools/gen-captions.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const groups = JSON.parse(readFileSync(join(root, "captions.json"), "utf8"));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const r = (n) => Math.round(n * 1000) / 1000;

const items = groups
  .map((g, i) => `      <div id="cap-${i}" class="clip cap" data-start="${g.start}" data-duration="${r(g.end - g.start)}"><span class="cap-t">${esc(g.text)}</span></div>`)
  .join("\n");
const tweens = groups
  .map((g, i) => {
    const d = r(g.end - g.start);
    return `    tl.fromTo("#cap-${i} .cap-t", { opacity: 0 }, { opacity: 1, duration: 0.1, ease: "power2.out" }, ${g.start});\n` +
      `    tl.to("#cap-${i} .cap-t", { opacity: 0, duration: 0.1, ease: "power2.in" }, ${r(g.start + d - 0.1)});`;
  })
  .join("\n");

const html = `<template>
  <style>
    #root {
      position: absolute;
      inset: 0;
      pointer-events: none;
    }
    .cap {
      position: absolute;
      left: 0;
      right: 0;
      bottom: 92px;
      text-align: center;
      overflow: visible;
    }
    .cap-t {
      display: inline-block;
      padding: 12px 28px 14px;
      border-radius: 14px;
      background: rgba(8, 20, 24, 0.86);
      border: 1px solid rgba(255, 255, 255, 0.08);
      color: #fff;
      font-family: "Inter", sans-serif;
      font-size: 46px;
      font-weight: 600;
      letter-spacing: -0.01em;
    }
  </style>
  <!-- Generated by tools/gen-captions.mjs from captions.json. Edit the JSON, not this file. -->
  <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
${items}
  </div>
  <script>
    const tl = gsap.timeline({ paused: true });
${tweens}
    window.__timelines["captions"] = tl;
  </script>
</template>
`;
writeFileSync(join(root, "compositions", "captions.html"), html);
console.log(`wrote ${groups.length} caption groups`);
